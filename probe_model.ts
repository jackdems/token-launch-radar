import { readFileSync } from 'node:fs';
import { fitCalibration, tvlReference, scoreProtocol, isPreToken, isRankable } from './lib/model.ts';
const snap = JSON.parse(readFileSync('token-radar-01-kit/input/snapshot.json','utf8'));
const cal = fitCalibration(snap);
const ref = tvlReference(snap, cal);
console.log('live_count', cal.live_count);
console.log('elasticity', cal.elasticity.toFixed(4));
console.log('base_multiple', cal.base_multiple.toFixed(4));
console.log('cv_r2', cal.cv_r2.toFixed(4), ' control_r2', cal.control_r2.toFixed(4));
console.log('median_abs_pct_err', (cal.median_abs_pct_error*100).toFixed(1)+'%');
console.log('growth_corr', cal.growth_correlation.toFixed(4));
console.log('tvl_ref', Math.round(ref));
console.log('cat tilts', Object.keys(cal.category_tilt).length);
const pre = snap.protocols.filter(isRankable);
const scored = pre.map((p:any)=>({slug:p.slug, tvl:p.tvl_usd, ...scoreProtocol(p, snap.as_of, cal, ref)}));
scored.sort((a:any,b:any)=>b.implied-a.implied);
console.log('\nTOP 8 implied:');
for (const s of scored.slice(0,8)) console.log(' ', s.slug.padEnd(24), 'tvl', String(s.tvl).padStart(12), 'implied', String(s.implied).padStart(13), 'mult', s.multiple.toFixed(3));
console.log('\nsanity: all implied positive?', scored.every((s:any)=>s.implied>0));
console.log('distinct values:', new Set(scored.map((s:any)=>s.implied)).size, 'of', scored.length);
